class TestGit(WsCase):
    @needs_git
    def test_save_commits_to_what_is_checked_out_and_still_guards_secrets(self):
        self.init_git()
        self.write("docs/product/n.md", "---\nkind: canon\ndescription: n\n---\n# N\n")
        self.assertEqual(self.ws("save", "-m", "docs: n", "--apply")[0], 0)           # git is history: no branch, no review gate
        self.assertEqual(self.git("rev-parse", "--abbrev-ref", "HEAD").strip(), "main")
        self.write("docs/product/m.md", "---\nkind: canon\ndescription: m\n---\n# M\n")
        self.assertEqual(self.ws("save", "docs", "-m", "docs: m", "--agent", "--apply")[0], 0)
        self.assertIn("AI-Assisted: yes", self.git("log", "-1", "--format=%B"))
        self.write("_workboard/leak.md", "---\nkind: working\ndescription: x\n---\npassword = hunter2hunter2\n")
        self.assertEqual(self.ws("save", "-m", "w: leak")[0], 2)                      # an unsure secret waits for the agent to decide

    @needs_git
    def test_archive_deletes_history_and_rewrites_citations(self):
        self.write("_workboard/meetings/m/transcript.md", "---\nkind: raw\ndescription: t\n---\nline\n")
        self.write("docs/product/p.md", "---\nkind: canon\ndescription: p\nderived_from: _workboard/meetings/m/transcript.md#L5\n---\n# P\n\n[m](../../_workboard/meetings/m/transcript.md)\n")
        self.init_git()
        self.assertEqual(self.ws("archive", "_workboard/meetings/m")[0], 0)  # dry run
        self.assertEqual(self.ws("archive", "_workboard/meetings/m", "--apply")[0], 2)  # needs the flag
        self.assertEqual(self.ws("archive", "_workboard/meetings/m", "--apply", "--yes-rewrite-history")[0], 0)
        self.assertEqual(self.git("log", "--all", "--oneline", "--", "_workboard/meetings/m").strip(), "")
        self.assertTrue((self.root / ".archive/_workboard/meetings/m/transcript.md").exists())
        self.assertIn(".archive/_workboard/meetings/m", self.read("docs/product/p.md"))
        self.assertEqual(self.git("status", "--porcelain").strip(), "")
        self.assertEqual(self.ws("check")[0], 0)

    @needs_git
    def test_archive_failure_leaves_nothing(self):
        self.init_git()
        self.write("loose.md", "x\n")
        self.assertEqual(self.ws("archive", "loose.md", "--apply", "--yes-rewrite-history")[0], 2)
        self.assertFalse((self.root / ".archive/loose.md").exists())

    def test_offload_verifies_then_deletes(self):
        self.init_git()
        self.write("_workboard/big.bin", "x" * 5000)
        dest = Path(self.tmp) / "cold"
        self.assertEqual(self.ws("git", "offload", "_workboard/big.bin", "--to", str(dest), "--apply")[0], 0)
        self.assertTrue((dest / "_workboard/big.bin").exists())
        self.assertFalse((self.root / "_workboard/big.bin").exists())
        self.assertIn("sha256=", self.read(".archive/manifest.md"))


