def needs_git(test):
    """For a test that runs git itself, outside WsCase.git and init_git (those skip on their own)."""
    return unittest.skipUnless(HAVE_GIT, "git is not installed")(test)



def ignore(d, names):
    gone = [n for n in names if n in (".git", "__pycache__", "cache", "backups", "snapshots", "reports")]
    if Path(d).resolve() == TEMPLATE:
        gone.append(".dev_yask")                                      # development files are not part of any project
    return gone + ([".ws"] if Path(d).name == "_steering" else [])   # the project's .ws is generated by the first ws run


class WsCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.root = Path(self.tmp) / "ws"
        shutil.copytree(TEMPLATE, self.root, ignore=ignore)
        self.env = dict(os.environ)
        self.old = os.getcwd()
        self.addCleanup(self.restore)   # a cleanup, not tearDown: it still runs when a subclass setUp skips (no git) or fails
        os.environ.pop("CI", None)   # tests are hermetic: a CI runner must not change what they exercise
        for k in GIT_LOCATION_VARS:   # nor may they inherit a repository, e.g. when the suite runs inside a git hook
            os.environ.pop(k, None)
        # nor the developer's own git setup (signed commits, a hooks path, useConfigOnly ...)
        os.environ.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", HOME=self.tmp, XDG_CONFIG_HOME=self.tmp)
        os.environ.update(WS_ROOT=str(self.root), WS_USER="ana", WS_NOW="20261115T0900Z", YASK_AUTOUPDATE="0", WS_NO_REEXEC="1", WS_UPDATE_SYNC="1", YASK_LIFECYCLE="0")
        os.chdir(self.root)

    def restore(self):
        os.chdir(self.old)
        os.environ.clear()
        os.environ.update(self.env)

    def ws(self, *argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                code = main(list(argv))
            except SystemExit as e:
                code = e.code
        return code, out.getvalue(), err.getvalue()

    def write(self, rel, text):
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

    def read(self, rel):
        return (self.root / rel).read_text(encoding="utf-8")

    def git(self, *a):
        if not HAVE_GIT:
            self.skipTest("git is not installed")
        return subprocess.run(["git", *a], cwd=self.root, capture_output=True, text=True).stdout

    def init_git(self):
        self.ws("modules")   # the first ws run generates _steering/.ws; commit it with the rest, as a project would
        if not HAVE_GIT:     # without git the workspace is still set up, and a test that needs the history is marked @needs_git
            return
        self.git("init", "-q", "-b", "main")
        self.git("config", "user.name", "ana")
        self.git("config", "user.email", "a@x")
        self.git("add", "-A")
        self.git("commit", "-qm", "init")


