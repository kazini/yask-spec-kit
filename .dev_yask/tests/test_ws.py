class TestModulesCommand(WsCase):
    def enabled(self):
        return yamlsub.loads(self.read("_steering/.ws/config.yaml"))["modules"]["enabled"]

    def test_a_module_is_disabled_and_enabled_again_and_the_router_follows(self):
        self.assertIn("software", self.ws("modules")[1])
        self.assertIn("software-standards.md", self.read("AGENTS.md"))
        code, out, _ = self.ws("modules", "disable", "software")                     # a preview changes nothing
        self.assertEqual(code, 0)
        self.assertIn("would disable software", out)
        self.assertIn("software", self.enabled())
        self.assertEqual(self.ws("modules", "disable", "software", "--apply")[0], 0)
        self.assertNotIn("software", self.enabled())
        self.assertNotIn("software-standards.md", self.read("AGENTS.md"))
        self.assertEqual(self.ws("modules", "enable", "software", "--apply")[0], 0)
        self.assertIn("software", self.enabled())
        self.assertIn("software-standards.md", self.read("AGENTS.md"))
        self.assertEqual(self.ws("check")[0], 0)

    def test_enabling_brings_what_the_module_requires(self):
        self.ws("modules", "disable", "software", "--apply")
        self.ws("modules", "disable", "decisions", "--apply")
        self.assertEqual(self.ws("modules", "enable", "software", "--apply")[0], 0)
        self.assertIn("decisions", self.enabled())

    def test_it_refuses_what_would_break_the_set(self):
        for argv, text in ((("disable", "knowledge"), "required by software"), (("disable", "core"), "core cannot be switched off"),
                           (("enable", "nope"), "unknown module"), (("disable", "lessons"), "already off")):
            code, out, err = self.ws("modules", *argv, "--apply")
            self.assertEqual(code, 2, argv)
            self.assertIn(text, out + err)
        self.assertIn("knowledge", self.enabled())


