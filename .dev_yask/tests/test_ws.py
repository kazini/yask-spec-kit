class TestIndex(WsCase):
    def open_index(self):
        from wslib.index import Index
        from wslib.repo import Repo
        ix = Index(Repo()).open()
        self.addCleanup(ix.db.close)
        return ix

    def dump(self, ix):
        return {t: sorted(tuple(r) for r in ix.db.execute(f"select * from {t}")) for t in ("files", "sections", "edges", "symbols", "sfts")}

    def test_markdown_only_update_matches_full_rebuild(self):
        self.write("code/lib/store.py", '"""Persistence."""\ndef save(r):\n    return check(r)\n\ndef check(r):\n    return r\n')
        self.write("code/api/app.js", "// API.\nexport function handle(x) { return save(x); }\n")
        self.write("docs/context/a.md", "---\nkind: canon\ndescription: a\n---\n# A\n\n## Alpha\nold\n")
        self.write("docs/product/p.md", "---\nkind: canon\ndescription: p\n---\n# P\n\nSee [a](../context/a.md#Alpha).\n")
        ix = self.open_index()
        ix.rebuild()
        self.assertFalse(ix.stale())
        ix.db.close()

        self.write("docs/context/a.md", "---\nkind: canon\ndescription: a\n---\n# A\n\n## Beta\nnew {#tolr-1234}\n")
        self.write("docs/product/p.md", "---\nkind: canon\ndescription: p\n---\n# P\n\nSee {tolr-1234}.\n")
        inc = self.open_index()
        self.assertTrue(inc.stale())
        self.assertTrue(inc._incremental_ok(inc.changed))    # no added/removed files, no code change
        inc.update(inc.changed)
        got = self.dump(inc)
        inc.db.close()

        full = self.open_index()
        full.rebuild()
        self.assertEqual(got, self.dump(full))                # same ids, edges, symbols and FTS rows as a full rebuild

    def test_code_change_takes_the_full_path(self):
        self.write("code/lib/store.py", "def alpha():\n    pass\n")
        ix = self.open_index()
        ix.rebuild()
        ix.db.close()

        self.write("code/lib/store.py", "def beta():\n    pass\n")
        ix = self.open_index()
        self.assertTrue(ix.stale())
        self.assertFalse(ix._incremental_ok(ix.changed))      # a code change affects global symbols and call confidence
        ix.ensure()
        names = {r[0] for r in ix.db.execute("select name from symbols")}
        self.assertIn("beta", names)
        self.assertNotIn("alpha", names)


